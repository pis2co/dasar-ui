// Single entry point: run `node scripts/docs-content.mjs` to refresh the committed docs content.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = path.join(root, 'projects/documentation/src/app');
function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(dir, entry.name);
    return entry.isDirectory() ? files(file) : [file];
  });
}
const sources = [path.join(app, 'app.ts'), ...files(path.join(app, 'pages')).filter(file => file.endsWith('.page.ts'))];
const keys = new Set();
for (const source of sources) {
  for (const match of readFileSync(source, 'utf8').matchAll(/getDocsContent\('([^']+)'\)/g)) keys.add(match[1]);
}
const entries = [...keys].sort().map(key => `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(path.join(root, key), 'utf8'))},`);
const output = `// Generated by scripts/docs-content.mjs; do not edit.\nexport const docsContent: Record<string, string> = {\n${entries.join('\n')}\n};\n\nexport function getDocsContent(path: string): string {\n  const content = docsContent[path];\n  if (content === undefined) throw new Error(\`Missing documentation content: \${path}\`);\n  return content;\n}\n`;
writeFileSync(path.join(app, 'docs-content.generated.ts'), output);
